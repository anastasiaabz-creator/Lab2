# Зчитування координат прямокутника та точки
x1 = int(input("Введіть X лівого верхнього кута: "))
y1 = int(input("Введіть Y лівого верхнього кута: "))
x2 = int(input("Введіть X правого нижнього кута: "))
y2 = int(input("Введіть Y правого нижнього кута: "))

# Зчитування координат точки
ax = int(input("Введіть X точки: "))
ay = int(input("Введіть Y точки : "))

# Перевірка належності точки прямокутнику
if x1 <= ax <= x2 and y2 <= ay <= y1:
    print("Yes")
else:
    print("No")

