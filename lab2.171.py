y1 = int(input("Введіть координату: "))
x2 = int(input("Введіть координату: "))
y2 = int(input("Введіть координату: "))
x3 = int(input("Введіть координату: "))
y3 = int(input("Введіть координату: "))

# Обчислення квадратів довжин сторін
a = (x2 - x1)**2 + (y2 - y1)**2
b = (x3 - x2)**2 + (y3 - y2)**2
c = (x1 - x3)**2 + (y1 - y3)**2

# Перевіряємо теорему Піфагора для кожної з трьох можливих гіпотенуз
if a + b == c or a + c == b or b + c == a:
    print("Yes")
else:
    print("No")

